test('logout em outra aba encerra acesso privado e preserva carrinho', async ({ page, context }) => {
  await page.goto('/login?redirect=%2Fpagamento')
  await login(page)
  await expect(page.getByTestId('payment-item')).toHaveCount(3)
  const other = await context.newPage()
  await other.goto('/pagamento')
  await expect(other.getByTestId('payment-item')).toHaveCount(3)
  await page.getByRole('button', { name: 'Conta', exact: true }).click()
  await page.getByRole('button', { name: 'Sair da conta', exact: true }).click()
  await expect(other.getByRole('heading', { name: 'Entre para continuar', exact: true })).toBeVisible()
  await expect(other.getByTestId('payment-item')).toHaveCount(0)
  await other.getByRole('link', { name: 'Entrar com e-mail e senha', exact: true }).click()
  await login(other)
  await expect(other.getByTestId('payment-item')).toHaveCount(3)
})

