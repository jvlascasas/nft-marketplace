import { expect, test, type Page } from '@playwright/test'
import path from 'node:path'

test.beforeEach(async ({ browserName }) => { test.skip(browserName !== 'chromium', 'Fluxos de conta em Chromium.') })
const originalPassword = 'Kurio@2026'
async function enter(page: Page, route = '/perfil', email = 'joao@kurio.test') {
  await page.goto('/login?redirect=' + encodeURIComponent(route))
  const dialog = page.getByRole('dialog', { name: 'Login', exact: true })
  await dialog.getByLabel('E-mail', { exact: true }).fill(email)
  await dialog.getByLabel('Senha', { exact: true }).fill(originalPassword)
  await dialog.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByRole('heading', { level: 1, name: route === '/carteiras' ? 'Carteira principal' : 'Perfil do colecionador', exact: true })).toBeVisible()
}
function profile(page: Page) { return page.locator('.profile-form') }
function primary(page: Page) { return page.getByRole('form', { name: 'Editar carteira principal', exact: true }) }
function secondary(page: Page) { return page.getByRole('form', { name: 'Editar carteira secundária', exact: true }) }
async function saveProfile(page: Page) {
  await profile(page).getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(profile(page).getByRole('status')).toContainText('atualizad')
}
async function signOut(page: Page) {
  await page.getByRole('navigation', { name: 'Menu da conta', exact: true }).locator('..').getByRole('button', { name: 'Sair', exact: true }).click()
  await expect(page).toHaveURL(/\/$/)
}

for (const route of ['/perfil', '/carteiras']) {
  test(route + ' exige sessão no acesso direto', async ({ page }) => {
    await page.goto(route)
    await expect(page.getByRole('heading', { name: 'Entre para acessar sua conta', exact: true })).toBeVisible()
    await page.getByRole('link', { name: 'Entrar para continuar', exact: true }).click()
    expect(new URL(page.url()).searchParams.get('redirect')).toBe(route)
  })
  test(route + ' segue o Figma desktop', async ({ page }, info) => {
    await enter(page, route)
    if (route === '/perfil') await expect(profile(page).getByLabel('Nome de exibição', { exact: false })).toHaveValue('João Moreira')
    else await expect(primary(page).getByLabel('Nome de exibição', { exact: false })).toHaveValue('João Moreira')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.evaluate(() => document.fonts.ready)
    if (info.project.name === 'desktop') await expect(page).toHaveScreenshot((route === '/perfil' ? 'profile' : 'wallets') + '.png', { fullPage: true, animations: 'disabled' })
    await page.screenshot({ path: info.outputPath(route.slice(1) + '-preview.png'), animations: 'disabled' })
  })
}

