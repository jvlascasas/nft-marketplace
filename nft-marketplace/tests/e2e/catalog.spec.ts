import { expect, test, type Page } from '@playwright/test'

async function openFilters(page: Page) {
  await expect(page.getByRole('button', { name: 'Todos os NFTs', exact: true })).toBeVisible()
  const trigger = page.getByRole('button', { name: 'Abrir filtros' })
  if (await trigger.isVisible()) await trigger.click()
}

async function closeFilters(page: Page) {
  const dialog = page.getByRole('dialog')
  if (await dialog.isVisible()) await dialog.getByRole('button', { name: 'Concluir' }).click()
}

test('combina filtros, busca e ordenação na URL e restaura histórico', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByTestId('nft-card')).toHaveCount(9)
  await openFilters(page)
  await page.getByRole('checkbox', { name: 'Arte digital', exact: true }).check()
  await page.getByRole('checkbox', { name: 'Ethereum', exact: true }).check()
  await closeFilters(page)
  await expect(page.getByTestId('nft-card')).toHaveCount(4)
  await page.getByRole('textbox', { name: 'Buscar NFTs' }).fill('Emerald')
  await page.getByRole('textbox', { name: 'Buscar NFTs' }).press('Enter')
  await expect(page.getByTestId('nft-card')).toHaveCount(2)
  if ((page.viewportSize()?.width ?? 1440) <= 640) await openFilters(page)
  await page.getByLabel('Ordenar por:').selectOption('price-desc')
  await closeFilters(page)
  await expect(page).toHaveURL(/price-desc/)
  await expect(page.getByTestId('nft-price').first()).toHaveText('1,19 ETH')
  await page.reload()
  await expect(page.getByRole('textbox', { name: 'Buscar NFTs' })).toHaveValue('Emerald')
  if ((page.viewportSize()?.width ?? 1440) <= 640) await openFilters(page)
  await expect(page.getByLabel('Ordenar por:')).toHaveValue('price-desc')
  await closeFilters(page)
  await expect(page.getByTestId('nft-card')).toHaveCount(2)
  await page.getByRole('button', { name: 'Limpar filtros', exact: true }).click()
  await expect(page.getByTestId('nft-card')).toHaveCount(9)
  await page.goBack()
  await expect(page.getByTestId('nft-card')).toHaveCount(2)
  await expect(page.getByRole('textbox', { name: 'Buscar NFTs' })).toHaveValue('Emerald')
})

