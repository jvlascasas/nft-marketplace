test('resposta lenta anterior não substitui a busca mais recente', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('nft-marketplace:scenario', 'variable-delay'))
  await page.goto('/')
  const input = page.getByRole('textbox', { name: 'Buscar NFTs' })
  await input.fill('a')
  await input.press('Enter')
  await input.fill('Golden')
  await input.press('Enter')
  await expect(page.getByTestId('nft-card')).toHaveCount(6)
  await expect(page.getByTestId('nft-card').first()).toContainText('Golden')
  // Let a subsequent request take the slower branch, then revisit the cached latest query.
  await page.goBack()
  await expect(input).toHaveValue('a')
  await page.goForward()
  await expect(input).toHaveValue('Golden')
  await expect(page.getByTestId('nft-card')).toHaveCount(6)
})

