test('faixa de preço permite arraste, teclado e sincroniza campos, URL e refresh', async ({ page }) => {
  await page.goto('/#catalogo')
  await openFilters(page)
  const lower = page.getByRole('slider', { name: 'Preço mínimo na faixa', exact: true })
  const upper = page.getByRole('slider', { name: 'Preço máximo na faixa', exact: true })
  await lower.scrollIntoViewIfNeeded()
  const track = await page.locator('.price-track:visible').boundingBox()
  if (!track) throw new Error('Faixa de preço não encontrada')
  await page.mouse.move(track.x, track.y + track.height / 2)
  await page.mouse.down()
  await page.mouse.move(track.x + track.width / 4, track.y + track.height / 2, { steps: 8 })
  await page.mouse.up()
  await expect(page.getByRole('textbox', { name: 'Mínimo', exact: true })).toHaveValue(/^2,[45]/)
  await page.getByRole('textbox', { name: 'Mínimo', exact: true }).fill('1,19')
  await page.getByRole('textbox', { name: 'Máximo', exact: true }).fill('3')
  await expect(lower).toHaveAttribute('aria-valuetext', '1,19 ETH')
  await lower.focus()
  await lower.press('ArrowRight')
  await expect(page.getByRole('textbox', { name: 'Mínimo', exact: true })).toHaveValue('1,2')
  await upper.focus()
  await upper.press('ArrowLeft')
  await expect(page.getByRole('textbox', { name: 'Máximo', exact: true })).toHaveValue('2,99')
  await page.getByRole('button', { name: 'Aplicar preço', exact: true }).click()
  await closeFilters(page)
  await expect.poll(() => JSON.parse(new URL(page.url()).searchParams.get('minPrice') ?? 'null')).toBe('1.2')
  expect(JSON.parse(new URL(page.url()).searchParams.get('maxPrice') ?? 'null')).toBe('2.99')
  await page.reload()
  await openFilters(page)
  await expect(lower).toHaveAttribute('aria-valuetext', '1,20 ETH')
  await upper.focus()
  await upper.press('End')
  await expect(page.getByRole('textbox', { name: 'Máximo', exact: true })).toHaveValue('')
  await expect(upper).toHaveAttribute('aria-valuetext', 'Sem limite')
  await upper.press('Home')
  await expect(page.getByRole('textbox', { name: 'Máximo', exact: true })).toHaveValue('1,2')
})

